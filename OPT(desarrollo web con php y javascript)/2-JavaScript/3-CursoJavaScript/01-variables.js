/* Para nombrar las variables usaremos el lower camel case:
helloWorld
*/
/* var: forma original de nombrar una variablev EN DESUSO
*/
var helloworld = "Hello, JavaScript"
console.log(helloworld)

var helloWorld = "Hola de nuevo, Javascript"
console.log(helloWorld)


// let: se puede reasignar su valor, funcionan dentro del ambito de aplicacion
let helloWorld2 = "Hola, JavaScript 2"
console.log(helloWorld2)

helloWorld2 = "Hola de nuevo, JavaScript 2"
console.log(helloWorld2)


// const: el valor que se le de en la declaracion sera el que tenga, no pudiendo ser reasignada
const helloWorld3 = "Hola, JavaScript 3"
console.log(helloWorld3)

helloWorld2 = "Hola de nuevo, JavaScript 3"
console.log(helloWorld3)
